  <h2>Cursos gratuitos com certificado 2026: o que você precisa saber</h2>

  <details class='faq-item'>
    <summary>O que são os cursos gratuitos do SENAC?</summary>
    <div class='faq-answer'>O SENAC oferece cursos gratuitos por meio do Programa Senac de Gratuidade (PSG), voltado a pessoas de baixa renda que desejam se qualificar profissionalmente. Os cursos abrangem áreas como administração, tecnologia, saúde, gastronomia, beleza e mais — nas modalidades presencial e online (EAD), com certificado reconhecido.</div>
  </details>

  <details class='faq-item'>
    <summary>Quem pode se inscrever nos cursos gratuitos?</summary>
    <div class='faq-answer'>Os cursos gratuitos do PSG são voltados a pessoas com renda familiar de até dois salários mínimos por pessoa. Além disso, é preciso atender aos pré-requisitos de cada curso, como idade mínima e escolaridade.</div>
  </details>

  <details class='faq-item'>
    <summary>Como se inscrever?</summary>
    <div class='faq-answer'>As inscrições são feitas online, pelo site oficial da instituição, ou presencialmente na unidade mais próxima. Em geral é necessário preencher um cadastro e apresentar documentos como RG, CPF e comprovante de residência. Os prazos e vagas variam por estado e por curso.</div>
  </details>

  <details class='faq-item'>
    <summary>Como conseguir um curso técnico de graça?</summary>
    <div class='faq-answer'>Além do SENAC e do SENAI, oferecem cursos técnicos gratuitos instituições como os Institutos Federais (IFs), a FAETEC, a Fundação Bradesco e programas do governo como o Pronatec. Muitos têm turmas a distância (EAD), o que amplia o acesso em todo o Brasil.</div>
  </details>

  <details class='faq-item'>
    <summary>Quais cursos gratuitos estão disponíveis?</summary>
    <div class='faq-answer'>Há opções em diversas áreas, entre as mais procuradas:
