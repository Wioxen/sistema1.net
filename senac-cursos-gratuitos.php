      </ul>
    </div>
  </details>

  <details class='faq-item'>
    <summary>Curso online ou presencial: qual escolher?</summary>
    <div class='faq-answer'>Os cursos online (EAD) oferecem flexibilidade para estudar no seu ritmo, com acesso ao conteúdo e certificado ao final — ideal para quem tem rotina apertada. Já os cursos presenciais são indicados para formações que exigem prática, como gastronomia, beleza e algumas áreas técnicas e industriais (SENAI).</div>
  </details>

